package neqsim.mcp.runners;

import java.util.Map;
import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import neqsim.mcp.model.ResultProvenance;
import neqsim.process.equipment.pipeline.TubingPerformance;
import neqsim.process.fielddevelopment.reservoir.RecombinationFluidFactory;
import neqsim.process.fielddevelopment.reservoir.TubingVlpProvider;
import neqsim.process.fielddevelopment.reservoir.VfpDeckReader;
import neqsim.process.fielddevelopment.reservoir.VfpTableBuilder;
import neqsim.thermo.system.SystemInterface;
import neqsim.thermo.system.SystemPrEos;
import neqsim.thermo.system.SystemSrkEos;

/**
 * Generates a VFPPROD lift curve table for Eclipse or OPM Flow from a well description in JSON.
 *
 * <p>
 * The runner wires {@link RecombinationFluidFactory} (surface gas, stock-tank liquid and water recombined for every
 * table coordinate), {@link TubingVlpProvider} (deviated tubing survey) and {@link VfpTableBuilder} (axes, rate cap,
 * sanity enforcement, deck text). It is the MCP face of the Java API; studies with their own flowline or topside models
 * should use {@link VfpTableBuilder} with a custom {@code VlpProvider} instead.
 * </p>
 *
 * <p>
 * Input fields: {@code wellType} (gas or oil), {@code tableNumber}, {@code datumDepth_m}, {@code unitSystem} (METRIC or
 * FIELD), {@code model} (SRK or PR), {@code gasComposition} and optional {@code liquidComposition} (mole amounts by
 * component), {@code includeWater}, {@code survey} (md_m, tvd_m, innerDiameter_m) or {@code tvd_m} with
 * {@code innerDiameter_m}, {@code correlation} (GRAY, BEGGS_BRILL, HASAN_KABIR, ...), {@code roughness_m},
 * {@code numberOfSegments}, {@code bottomholeTemperature_C}, {@code wellheadTemperature_C}, {@code axes} (rates_Sm3d,
 * outletPressures_bara, waterRatios, gasRatios), optional {@code rateCap} (maxRate_Sm3d, penaltyBarPer100Percent),
 * {@code failurePolicy}, {@code zeroRatioFloor}, {@code title} and {@code provenance}.
 * </p>
 *
 * @author ESOL
 * @version 1.0
 */
public class VfpTableRunner {
  private static final Gson GSON = new GsonBuilder().setPrettyPrinting().serializeSpecialFloatingPointValues().create();

  /** Utility class; not instantiable. */
  private VfpTableRunner() {
  }

  /**
   * Builds a VFPPROD table.
   *
   * @param json JSON well and table specification
   * @return JSON with status, the deck text, the pressure table, warnings and validation figures
   */
  public static String run(String json) {
    if (json == null || json.trim().isEmpty()) {
      return errorJson("INPUT_ERROR", "JSON input is null or empty", "Provide a VFP table specification");
    }
    JsonObject input;
    try {
      input = JsonParser.parseString(json).getAsJsonObject();
    } catch (Exception e) {
      return errorJson("JSON_PARSE_ERROR", "Failed to parse JSON: " + e.getMessage(), "Ensure the JSON is well-formed");
    }
    long start = System.currentTimeMillis();
    try {
      if (!input.has("gasComposition")) {
        return errorJson("MISSING_GAS_COMPOSITION", "No 'gasComposition' specified",
            "Provide the surface gas composition as component to mole amount");
      }
      if (!input.has("axes")) {
        return errorJson("MISSING_AXES", "No 'axes' specified",
            "Provide axes with rates_Sm3d and outletPressures_bara (waterRatios and gasRatios optional)");
      }
      boolean gasWell = !"oil".equalsIgnoreCase(getString(input, "wellType", "gas"));
      int tableNumber = (int) getDouble(input, "tableNumber", 1.0);
      VfpTableBuilder builder = gasWell ? VfpTableBuilder.gasWell(tableNumber) : VfpTableBuilder.oilWell(tableNumber);
      builder.setDatumDepth(getDouble(input, "datumDepth_m", 0.0));
      builder.setUnitSystem(getString(input, "unitSystem", "METRIC"));
      builder.setTitle(getString(input, "title", "VFP table generated by NeqSim"));
      if (input.has("provenance")) {
        for (JsonElement line : input.getAsJsonArray("provenance")) {
          builder.addProvenance(line.getAsString());
        }
      }

      JsonObject axes = input.getAsJsonObject("axes");
      builder.setRates(array(axes, "rates_Sm3d"));
      builder.setOutletPressures(array(axes, "outletPressures_bara"));
      if (axes.has("waterRatios")) {
        builder.setWaterRatios(array(axes, "waterRatios"));
      }
      if (axes.has("gasRatios")) {
        builder.setGasRatios(array(axes, "gasRatios"));
      }
      if (input.has("rateCap")) {
        JsonObject cap = input.getAsJsonObject("rateCap");
        builder.setRateCap(cap.get("maxRate_Sm3d").getAsDouble(),
            cap.has("penaltyBarPer100Percent") ? cap.get("penaltyBarPer100Percent").getAsDouble() : 200.0);
      }
      if ("EXTRAPOLATE_RATE".equalsIgnoreCase(getString(input, "failurePolicy", "FAIL"))) {
        builder.setFailurePolicy(VfpTableBuilder.FailurePolicy.EXTRAPOLATE_RATE);
      }
      builder.setZeroRatioFloor(getDouble(input, "zeroRatioFloor", 0.0));

      String model = getString(input, "model", "SRK").toUpperCase();
      SystemInterface template = "PR".equals(model) ? new SystemPrEos(358.15, 200.0) : new SystemSrkEos(358.15, 200.0);
      SystemInterface gas = composition(model, input.getAsJsonObject("gasComposition"));
      SystemInterface liquid = input.has("liquidComposition")
          ? composition(model, input.getAsJsonObject("liquidComposition"))
          : null;
      addComponents(template, input.getAsJsonObject("gasComposition"));
      if (liquid != null) {
        addComponents(template, input.getAsJsonObject("liquidComposition"));
      }
      if (!input.has("includeWater") || input.get("includeWater").getAsBoolean()) {
        if (!template.hasComponent("water")) {
          template.addComponent("water", 1.0e-6);
        }
      }
      template.setMixingRule(FluidDefaults.resolveMixingRule(input, model));
      template.setMultiPhaseCheck(true);

      RecombinationFluidFactory factory = new RecombinationFluidFactory(template, gas, liquid);
      if (gasWell) {
        factory.setRateBasis("GAS").setWaterRatioType("WGR").setGasRatioType("OGR");
      } else {
        factory.setRateBasis("OIL").setWaterRatioType("WCT").setGasRatioType("GOR");
      }

      TubingVlpProvider provider = createProvider(input, factory);
      VfpTableBuilder.Result result = builder.build(provider);

      JsonObject data = new JsonObject();
      String deck = result.toDeckString();
      data.addProperty("deck", deck);
      data.addProperty("tableNumber", tableNumber);
      data.add("rates_Sm3d", toArray(result.getRates()));
      data.add("outletPressures_bara", toArray(result.getOutletPressures()));
      data.add("waterRatios", toArray(result.getWaterRatios()));
      data.add("gasRatios", toArray(result.getGasRatios()));
      data.add("bhp_bara", GSON.toJsonTree(result.getBhpArray()));
      JsonArray warnings = new JsonArray();
      for (String w : result.getWarnings()) {
        warnings.add(w);
      }
      data.add("warnings", warnings);
      JsonObject validation = new JsonObject();
      validation.addProperty("repairedPoints", result.getRepairCount());
      validation.addProperty("rateCapPoints", result.getCapPointCount());
      validation.addProperty("extrapolatedPoints", result.getExtrapolatedCount());
      validation.addProperty("providerEvaluations", provider.getEvaluations());
      validation.addProperty("providerFailures", provider.getFailures());
      if ("METRIC".equalsIgnoreCase(getString(input, "unitSystem", "METRIC"))) {
        validation.addProperty("deckRoundTripMaxAbsError_bara", roundTripError(deck, result));
      }
      data.add("validation", validation);

      JsonObject out = new JsonObject();
      out.addProperty("status", "success");
      out.add("data", data);
      ResultProvenance provenance = new ResultProvenance();
      provenance.setCalculationType("VFPPROD from tubing survey lift model (screening, calibrate before use)");
      provenance.setConverged(provider.getFailures() == 0);
      provenance.setComputationTimeMs(System.currentTimeMillis() - start);
      out.add("provenance", GSON.toJsonTree(provenance));
      return GSON.toJson(out);
    } catch (IllegalArgumentException | IllegalStateException e) {
      return errorJson("VFP_INPUT_ERROR", "VFP table generation failed: " + e.getMessage(),
          "Check axes, composition and the failurePolicy setting");
    } catch (Exception e) {
      return errorJson("VFP_ERROR", "VFP table generation failed: " + e.getMessage(),
          "Check the well description and fluid definition");
    }
  }

  /**
   * Creates the tubing lift model from the well fields of the request.
   *
   * @param input request JSON
   * @param factory well stream factory
   * @return configured provider
   */
  private static TubingVlpProvider createProvider(JsonObject input, RecombinationFluidFactory factory) {
    TubingVlpProvider provider;
    if (input.has("survey")) {
      JsonObject s = input.getAsJsonObject("survey");
      provider = new TubingVlpProvider(factory, array(s, "md_m"), array(s, "tvd_m"), array(s, "innerDiameter_m"));
    } else {
      provider = new TubingVlpProvider(factory, getDouble(input, "tvd_m", 2500.0),
          getDouble(input, "innerDiameter_m", 0.1));
    }
    provider.setTemperatures(getDouble(input, "bottomholeTemperature_C", 90.0),
        getDouble(input, "wellheadTemperature_C", 40.0));
    provider.setNumberOfSegments((int) getDouble(input, "numberOfSegments", 6.0));
    provider.setRoughness(getDouble(input, "roughness_m", 2.5e-5));
    provider.setCorrelation(
        TubingPerformance.CorrelationType.valueOf(getString(input, "correlation", "GRAY").toUpperCase()));
    return provider;
  }

  /**
   * Creates a surface-condition fluid from a composition object.
   *
   * @param model SRK or PR
   * @param comps component to mole amount
   * @return fluid with the components added
   */
  private static SystemInterface composition(String model, JsonObject comps) {
    SystemInterface fluid = "PR".equals(model) ? new SystemPrEos(288.15, 1.01325) : new SystemSrkEos(288.15, 1.01325);
    addComponents(fluid, comps);
    return fluid;
  }

  /**
   * Adds the components of a composition object that the fluid does not have yet.
   *
   * @param fluid fluid to extend
   * @param comps component to mole amount
   */
  private static void addComponents(SystemInterface fluid, JsonObject comps) {
    for (Map.Entry<String, JsonElement> entry : comps.entrySet()) {
      if (!fluid.hasComponent(entry.getKey())) {
        fluid.addComponent(entry.getKey(), entry.getValue().getAsDouble());
      }
    }
  }

  /**
   * Parses the deck text and returns the largest difference to the table.
   *
   * @param deck deck text in metric units
   * @param result built table
   * @return largest absolute pressure difference in bar
   */
  private static double roundTripError(String deck, VfpTableBuilder.Result result) {
    double[][][][][] parsed = VfpDeckReader.parse(deck).getBhp();
    double max = 0.0;
    for (int f = 0; f < parsed.length; f++) {
      for (int t = 0; t < parsed[f].length; t++) {
        for (int w = 0; w < parsed[f][t].length; w++) {
          for (int g = 0; g < parsed[f][t][w].length; g++) {
            max = Math.max(max, Math.abs(parsed[f][t][w][g][0] - result.getBhp(f, t, w, g, 0)));
          }
        }
      }
    }
    return max;
  }

  /**
   * Reads a numeric array from a JSON object.
   *
   * @param object JSON object
   * @param name property name
   * @return values
   * @throws IllegalArgumentException if the property is missing
   */
  private static double[] array(JsonObject object, String name) {
    JsonArray values = object.getAsJsonArray(name);
    if (values == null) {
      throw new IllegalArgumentException("Missing array '" + name + "'");
    }
    double[] out = new double[values.size()];
    for (int i = 0; i < out.length; i++) {
      out[i] = values.get(i).getAsDouble();
    }
    return out;
  }

  /**
   * Converts values to a JSON array.
   *
   * @param values values
   * @return JSON array
   */
  private static JsonArray toArray(double[] values) {
    JsonArray array = new JsonArray();
    for (double v : values) {
      array.add(v);
    }
    return array;
  }

  /**
   * Reads an optional string property.
   *
   * @param object JSON object
   * @param name property name
   * @param fallback value when absent
   * @return property value or fallback
   */
  private static String getString(JsonObject object, String name, String fallback) {
    return object.has(name) ? object.get(name).getAsString() : fallback;
  }

  /**
   * Reads an optional number property.
   *
   * @param object JSON object
   * @param name property name
   * @param fallback value when absent
   * @return property value or fallback
   */
  private static double getDouble(JsonObject object, String name, double fallback) {
    return object.has(name) ? object.get(name).getAsDouble() : fallback;
  }

  /**
   * Creates the standard error response.
   *
   * @param code error code
   * @param message error message
   * @param remediation fix suggestion
   * @return error JSON
   */
  private static String errorJson(String code, String message, String remediation) {
    JsonObject error = new JsonObject();
    error.addProperty("status", "error");
    JsonArray errors = new JsonArray();
    JsonObject err = new JsonObject();
    err.addProperty("code", code);
    err.addProperty("message", message);
    err.addProperty("remediation", remediation);
    errors.add(err);
    error.add("errors", errors);
    return GSON.toJson(error);
  }
}
