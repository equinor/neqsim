  /**
   * Serialize accepted pipe/disc/work and replay identical requests, including contact and remainder.
   *
   * @throws Exception if serialization fails
   */
  @Test
  void deterministicRestartAndHistoryOwnership() throws Exception {
    WaterHammerPipe pipe = pipe(51, 0.2, 2.0);
    pipe.setUpstreamBoundary("CLOSED_END");
    pipe.runTransient(0.09, UUID.randomUUID());
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    try (ObjectOutputStream output = new ObjectOutputStream(bytes)) {
      output.writeObject(pipe);
    }
    WaterHammerPipe copy;
    try (ObjectInputStream input = new ObjectInputStream(new ByteArrayInputStream(bytes.toByteArray()))) {
      copy = (WaterHammerPipe) input.readObject();
    }
    for (int i = 0; i < 300; i++) {
      pipe.runTransient(1e-4, UUID.randomUUID());
      copy.runTransient(1e-4, UUID.randomUUID());
    }
    assertTrue(pipe.getLiftContactCount() > 0);
    assertEquals(pipe.getLiftContactCount(), copy.getLiftContactCount());
    assertEquals(pipe.getLastLiftContactTime(), copy.getLastLiftContactTime(), 0.0);
    assertArrayEquals(pipe.getCellPressureProfile(), copy.getCellPressureProfile(), 0.0);
    assertArrayEquals(pipe.getCellFlowProfile(), copy.getCellFlowProfile(), 0.0);
    assertEquals(pipe.getLiftPosition(), copy.getLiftPosition(), 0.0);
    assertEquals(pipe.getLiftVelocity(), copy.getLiftVelocity(), 0.0);
    assertEquals(pipe.getLiftPressureWork(), copy.getLiftPressureWork(), 0.0);
    assertEquals(pipe.getLiftEnergyResidual(), copy.getLiftEnergyResidual(), 0.0);
    for (int i = 0; i < pipe.getLiftHistory().size(); i++) {
      assertArrayEquals(pipe.getLiftHistory().get(i), copy.getLiftHistory().get(i), 0.0);
    }
    double original = pipe.getLiftHistory().get(0)[1];
    pipe.getLiftHistory().get(0)[1] = 99.0;
    assertEquals(original, pipe.getLiftHistory().get(0)[1], 0.0);
  }

