  /**
   * Execute inlet isolation and retain pressure, reverse-flow, contact and conservation evidence.
   *
   * @param nodes physical faces
   * @param dt external timestep, s
   * @param mass translating mass, kg
   * @param damping damping, N s/m
   * @return named measured results
   */
  private static JsonObject isolation(int nodes, double dt, double mass, double damping) {
    WaterHammerPipe pipe = pipe(nodes, mass, damping);
    pipe.setUpstreamBoundary("CLOSED_END");
    double minimumJet = 0.0;
    double firstContactTime = Double.NaN;
    double firstImpactLoss = Double.NaN;
    double maximumEnergyResidual = 0.0;
    double maximumVolumeResidual = 0.0;
    double maximumMomentumResidual = 0.0;
    for (int i = 1; i <= Math.round(0.5 / dt); i++) {
      double end = i == Math.round(0.5 / dt) ? 0.5 : i * dt;
      pipe.runTransient(end - pipe.getCurrentTime(), UUID.randomUUID());
      maximumEnergyResidual = Math.max(maximumEnergyResidual, Math.abs(pipe.getLiftEnergyResidual()));
      maximumVolumeResidual = Math.max(maximumVolumeResidual, Math.abs(pipe.getAcousticVolumeResidual()));
      maximumMomentumResidual = Math.max(maximumMomentumResidual, Math.abs(pipe.getMomentumResidual()));
      assertTrue(pipe.getLiftPosition() >= 0.0 && pipe.getLiftPosition() <= 0.01);
    }
    for (double[] row : pipe.getLiftHistory()) {
      if (row[1] > 0.0) {
        minimumJet = Math.min(minimumJet, row[8]);
      }
      if (!Double.isFinite(firstContactTime) && row[11] == 1.0) {
        firstContactTime = row[0];
        firstImpactLoss = row[7];
      }
    }
    assertEquals(0.5, pipe.getCurrentTime(), 0.0);
    assertTrue(minimumJet < 0.0, "Reverse flow before contact");
    assertTrue(pipe.getLiftContactCount() > 0);
    assertTrue(pipe.getLiftImpactLoss() > 0.0);
    assertTrue(maximumEnergyResidual <= 1e-10);
    assertTrue(maximumVolumeResidual <= 1e-9);
    assertTrue(maximumMomentumResidual <= 1e-7);
    JsonObject row = new JsonObject();
    row.addProperty("nodes", nodes);
    row.addProperty("dt_s", dt);
    row.addProperty("mass_kg", mass);
    row.addProperty("damping_N_s_m", damping);
    row.addProperty("minimumPreSeatJet_m3_s", minimumJet);
    row.addProperty("lastContactTime_s", pipe.getLastLiftContactTime());
    row.addProperty("firstContactTime_s", firstContactTime);
    row.addProperty("firstImpactLoss_J", firstImpactLoss);
    row.addProperty("courantNumber", dt * 1000.0 / (100.0 / (nodes - 1)));
    row.addProperty("contactCount", pipe.getLiftContactCount());
    row.addProperty("minimumPressure_bara", pipe.getMinPressure() / 1e5);
    row.addProperty("maximumPressure_bara", pipe.getMaxPressure() / 1e5);
    row.addProperty("impactLoss_J", pipe.getLiftImpactLoss());
    row.addProperty("dampingLoss_J", pipe.getLiftDampingLoss());
    row.addProperty("numericalLoss_J", pipe.getLiftNumericalLoss());
    row.addProperty("maximumEnergyResidual_J", maximumEnergyResidual);
    row.addProperty("maximumVolumeResidual_m3", maximumVolumeResidual);
    row.addProperty("maximumMomentumResidual_kg_m_s", maximumMomentumResidual);
    return row;
  }

