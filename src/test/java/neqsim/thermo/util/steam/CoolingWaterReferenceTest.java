package neqsim.thermo.util.steam;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import org.junit.jupiter.api.Test;
import neqsim.thermo.system.SystemSeawater;
import neqsim.thermodynamicoperations.ThermodynamicOperations;

/**
 * Independent published IAPWS check values and thermodynamic identities for cooling utilities.
 *
 * @author Even Solbraa
 * @version 1.0
 */
class CoolingWaterReferenceTest {
  /** Checks R12-08 and R15-11 Table 4 values, not values generated by this implementation. */
  @Test
  void publishedWaterTransportCheckValues() {
    assertEquals(889.735100e-6, CoolingWaterTransport.waterViscosity(298.15, 998.0), 1e-12);
    assertEquals(1437.649467e-6, CoolingWaterTransport.waterViscosity(298.15, 1200.0), 1e-12);
    assertEquals(0.607712868, CoolingWaterTransport.waterConductivity(298.15, 998.0), 1e-9);
    assertEquals(0.799038144, CoolingWaterTransport.waterConductivity(298.15, 1200.0), 1e-9);
  }

  /** Checks every saline increment in IAPWS G10-15 Table 2, including elevated pressure. */
  @Test
  void publishedSeawaterConductivityCheckValues() {
    double[][] data = {{293.15, 0.1, 35.0, -0.004186040}, {293.15, 120.0, 35.0, -0.004317350},
        {333.15, 0.1, 35.0, -0.004124057}, {333.15, 120.0, 35.0, -0.004264405}, {293.15, 0.1, 100.0, -0.013819821},
        {373.15, 1.0, 100.0, -0.013094107}, {293.15, 0.1, 120.0, -0.017005302}, {293.15, 120.0, 120.0, -0.020194816},
        {333.15, 120.0, 120.0, -0.019722469}};
    for (double[] row : data) {
      assertEquals(row[3], CoolingWaterTransport.seawaterConductivityIncrement(row[0], row[1], row[2]), 1e-9);
    }
  }

  /** Checks AN5-13(2016) Table A1, with its IF97 water reference and solution mass basis. */
  @Test
  void industrialSeawaterPublishedGibbsChecks() {
    double temperature = 273.15;
    double pressure = 1.01325;
    double salinity = 35.16504;
    assertEquals(-101.342742, SeawaterProperties.salineGibbsDerivative(temperature, pressure, salinity, 0, 0), 1e-6);
    assertEquals(0.972659995e-3, SeawaterProperties.gibbsDerivative(temperature, pressure, salinity, 0, 1), 1e-12);
    assertEquals(-0.450731982e-12, SeawaterProperties.gibbsDerivative(temperature, pressure, salinity, 0, 2), 1e-21);
    assertEquals(0.515875254e-7, SeawaterProperties.gibbsDerivative(temperature, pressure, salinity, 1, 1), 1e-15);
    assertEquals(3986.47132, SeawaterProperties.specificHeatCapacity(temperature, pressure, salinity), 1e-5);
    assertEquals(-0.0019918, SeawaterProperties.specificEnthalpy(temperature, pressure, salinity), 1e-6);
    SystemSeawater fluid = new SystemSeawater(temperature, pressure, salinity);
    new ThermodynamicOperations(fluid).TPflash();
    assertEquals(1449.07123, fluid.getPhase(0).getSoundSpeed(), 1e-5);

    // Table A1's concentrated, high-temperature point has extrapolated pressure derivatives.
    assertEquals(294299.945, SeawaterProperties.specificEnthalpy(353.0, pressure, 100.0), 0.001);
    assertEquals(3743.82192, SeawaterProperties.specificHeatCapacity(353.0, pressure, 100.0), 1e-5);
    assertFalse(SeawaterProperties.isWithinPressureReferenceRange(353.0, 100.0));
    assertTrue(SeawaterProperties.isWithinPressureReferenceRange(298.15, 35.16504));
  }

  /** Checks caloric consistency across nearby temperature, pressure and salinity states. */
  @Test
  void enthalpyDerivativeEqualsHeatCapacity() {
    for (double temperature : new double[] {278.15, 298.15, 323.15, 348.15}) {
      for (double pressure : new double[] {1.01325, 5.0, 100.0}) {
        for (double salinity : new double[] {0.0, 35.0, 120.0}) {
          double step = 0.001;
          double numerical = (SeawaterProperties.specificEnthalpy(temperature + step, pressure, salinity)
              - SeawaterProperties.specificEnthalpy(temperature - step, pressure, salinity)) / (2.0 * step);
          assertEquals(numerical, SeawaterProperties.specificHeatCapacity(temperature, pressure, salinity), 0.001);
        }
      }
    }
  }

  /** Checks separate iapws 1.5.5 SeaWater(IF97=True) results, including elevated pressure. */
  @Test
  void independentImplementationPressureGrid() {
    // T [K], P [bara], rho [kg/m3], h [J/kg], Cp [J/(kg K)]; S = 35 g/kg solution.
    double[][] data = {{278.15, 1.01325, 1027.5456828557083, 19941.291344580783, 3988.4006961168175},
        {278.15, 5.0, 1027.730343171607, 20316.964587199556, 3987.1847339312135},
        {278.15, 50.0, 1029.804123793878, 24545.930841125384, 3973.7468707716375},
        {298.15, 1.01325, 1023.2199544694719, 99830.54397629676, 4000.348787125227},
        {298.15, 5.0, 1023.3915290508094, 100185.61585165327, 3999.446493576926},
        {298.15, 50.0, 1025.3192520711043, 104186.61191925676, 3989.441549948498},
        {308.15, 1.01325, 1019.8130510856626, 139855.25389753893, 4004.3501304698584},
        {308.15, 5.0, 1019.9815376935264, 140201.81341244854, 4003.552539456112},
        {308.15, 50.0, 1021.874753708122, 144108.25513338143, 3994.6726095128784}};
    for (double[] row : data) {
      SystemSeawater fluid = new SystemSeawater(row[0], row[1], 35.0);
      new ThermodynamicOperations(fluid).TPflash();
      fluid.initProperties();
      assertEquals(row[2], fluid.getDensity("kg/m3"), 1e-7);
      assertEquals(row[3], fluid.getEnthalpy("J/kg"), 1e-6);
      assertEquals(row[4], fluid.getCp("J/kgK"), 1e-7);
    }
  }

  /** Rejects unsupported states and non-finite inputs instead of extrapolating silently outside the envelope. */
  @Test
  void invalidInputsAreRejected() {
    assertThrows(IllegalArgumentException.class, () -> new SystemSeawater(260.0, 3.0, 35.0));
    assertThrows(IllegalArgumentException.class, () -> new SystemSeawater(298.15, 0.2, 35.0));
    assertThrows(IllegalArgumentException.class, () -> new SystemSeawater(298.15, 3.0, Double.NaN));
    assertThrows(IllegalArgumentException.class, () -> new SystemSeawater(298.15, 3.0, 121.0));
    assertThrows(IllegalArgumentException.class,
        () -> SeawaterProperties.salineGibbsDerivative(298.15, 3.0, 35.0, -1, 0));
  }
}
